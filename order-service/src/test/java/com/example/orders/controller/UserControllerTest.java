package com.example.orders.controller;

import com.example.orders.exception.EmailInUseException;
import com.example.orders.exception.UserHasOrdersException;
import com.example.orders.exception.UserNotFoundException;
import com.example.orders.model.User;
import com.example.orders.service.OrderService;
import com.example.orders.service.UserService;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.WebMvcTest;
import org.springframework.http.MediaType;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.test.web.servlet.MockMvc;

import java.util.UUID;

import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.doThrow;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.delete;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.header;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/** Web layer only: routing, validation, status codes and JSON shape. The services are mocked. */
@WebMvcTest(UserController.class)
class UserControllerTest {

    @Autowired MockMvc mvc;
    @MockitoBean UserService users;
    @MockitoBean OrderService orders;

    private static final UUID ID = UUID.fromString("00000000-0000-4000-8000-000000000001");

    private static User user() {
        User user = new User("Maya Okafor", "maya@example.com", "Lumen Labs", "18 Harbour St", "Europe/London", true);
        ReflectionTestUtils.setField(user, "id", ID);   // normally generated by JPA
        return user;
    }

    @Test
    void get_returnsUserJson() throws Exception {
        when(users.get(ID)).thenReturn(user());

        mvc.perform(get("/users/{id}", ID))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.id").value(ID.toString()))
                .andExpect(jsonPath("$.name").value("Maya Okafor"))
                .andExpect(jsonPath("$.email").value("maya@example.com"))
                .andExpect(jsonPath("$.company").value("Lumen Labs"))
                .andExpect(jsonPath("$.address").value("18 Harbour St"))
                .andExpect(jsonPath("$.timezone").value("Europe/London"))
                .andExpect(jsonPath("$.enrolled").value(true));
    }

    @Test
    void get_unknownUser_is404() throws Exception {
        when(users.get(ID)).thenThrow(new UserNotFoundException(ID));
        mvc.perform(get("/users/{id}", ID)).andExpect(status().isNotFound());
    }

    @Test
    void get_notAUuid_is400() throws Exception {
        mvc.perform(get("/users/not-a-uuid")).andExpect(status().isBadRequest());
    }

    @Test
    void create_returns201WithLocation() throws Exception {
        when(users.create(any())).thenReturn(user());

        mvc.perform(post("/users").contentType(MediaType.APPLICATION_JSON)
                        .content("{\"name\":\"Maya Okafor\",\"email\":\"maya@example.com\"}"))
                .andExpect(status().isCreated())
                .andExpect(header().string("Location", "/users/" + ID))
                .andExpect(jsonPath("$.id").value(ID.toString()));
    }

    @Test
    void create_invalidInput_is400AndNeverReachesTheService() throws Exception {
        String[] invalidBodies = {
                "{\"name\":\"\",\"email\":\"maya@example.com\"}",                              // blank name
                "{\"name\":\"Maya\",\"email\":\"not-an-email\"}",                              // bad email
                "{\"name\":\"Maya\",\"email\":\"maya@example.com\",\"timezone\":\"Mars/Olympus\"}",
                "{\"name\":\"Maya\",\"email\":\"maya@example.com\",\"address\":\"" + "a".repeat(501) + "\"}",
        };
        for (String body : invalidBodies) {
            mvc.perform(post("/users").contentType(MediaType.APPLICATION_JSON).content(body))
                    .andExpect(status().isBadRequest());
        }
        verify(users, never()).create(any());
    }

    @Test
    void update_duplicateEmail_is409() throws Exception {
        when(users.update(eq(ID), any())).thenThrow(new EmailInUseException("taken@example.com"));

        mvc.perform(put("/users/{id}", ID).contentType(MediaType.APPLICATION_JSON)
                        .content("{\"name\":\"Maya\",\"email\":\"taken@example.com\",\"timezone\":\"UTC\",\"enrolled\":true}"))
                .andExpect(status().isConflict());
    }

    @Test
    void update_missingEnrolled_is400() throws Exception {
        mvc.perform(put("/users/{id}", ID).contentType(MediaType.APPLICATION_JSON)
                        .content("{\"name\":\"Maya\",\"email\":\"maya@example.com\",\"timezone\":\"UTC\"}"))
                .andExpect(status().isBadRequest());
    }

    @Test
    void delete_returns204() throws Exception {
        mvc.perform(delete("/users/{id}", ID)).andExpect(status().isNoContent());
        verify(users).delete(ID);
    }

    @Test
    void delete_userWithOrders_is409() throws Exception {
        doThrow(new UserHasOrdersException(ID, 3)).when(users).delete(ID);
        mvc.perform(delete("/users/{id}", ID)).andExpect(status().isConflict());
    }
}
